/**
 * The generator's seeded randomness (scripts/gen/core mulberry32), for the
 * templates that vary with a seed of their own (Your Taste's jitter): the
 * same seed, the same drawing, on every device.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
